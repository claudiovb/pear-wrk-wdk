const fs = require('fs')
const path = require('path')
const Hyperschema = require('hyperschema')
const HRPCBuilder = require('hrpc')

/**
 * Generates the HRPC files from schema.json and hrpc.json:
 * - <outputDir>/messages.js (from schema.json via hyperschema)
 * - <outputDir>/index.js (from hrpc.json via the hrpc compiler)
 * - <schemaDir>/index.js (from schema.json via hyperschema)
 *
 * @param {Object} options
 * @param {{ version?: number, schema: Object[] }} options.schemaData - The parsed schema.json.
 * @param {string} options.schemaDir - The directory hyperschema writes its own output to.
 * @param {string} options.hrpcDir - The directory that contains hrpc.json.
 * @param {string} options.outputDir - The directory the HRPC files are written to.
 */
function generateHrpc ({ schemaData, schemaDir, hrpcDir, outputDir }) {
  const hrpcMessagesPath = path.join(outputDir, 'messages.js')

  // Start from an empty schema directory. hyperschema keeps its own version counter
  // there, and a counter left by an earlier run changes the code it generates, so the
  // output would differ from one machine to the next. Does nothing if it is not there.
  fs.rmSync(schemaDir, { recursive: true, force: true })

  // Try to load existing schema from directory, or create new one
  let schema
  try {
    schema = Hyperschema.from(schemaDir)
  } catch (err) {
    // If directory doesn't exist or schema can't be loaded, create new
    schema = new Hyperschema()
  }

  // Get or create namespace
  const ns = schema.namespace('wdk-core')

  // Process each schema definition
  for (const def of schemaData.schema) {
    if (def.enum) {
      // Handle enum - register with enum property
      ns.register({
        name: def.name,
        enum: def.enum.map(e => e.key),
        offset: def.offset !== undefined ? def.offset : 1
      })
    } else if (def.fields) {
      // Handle struct
      ns.register({
        name: def.name,
        compact: def.compact !== undefined ? def.compact : false,
        flagsPosition: def.flagsPosition !== undefined ? def.flagsPosition : 0,
        fields: def.fields.map(field => ({
          name: field.name,
          type: field.type,
          required: field.required !== undefined ? field.required : false,
          array: field.array !== undefined ? field.array : false
        }))
      })
    }
  }

  // Ensure output directories exist
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true })
  }
  if (!fs.existsSync(schemaDir)) {
    fs.mkdirSync(schemaDir, { recursive: true })
  }

  // Generate schema files
  // This will write to generated/schema/index.js and generated/schema/schema.json
  Hyperschema.toDisk(schema, { filename: path.join(schemaDir, 'index.js') })

  // Also copy the generated file to generated/hrpc/messages.js
  // (since both seem to use the same schema)
  if (fs.existsSync(path.join(schemaDir, 'index.js'))) {
    const generatedContent = fs.readFileSync(path.join(schemaDir, 'index.js'), 'utf8')
    // Update the comment to indicate it's for hrpc messages
    const updatedContent = generatedContent.replace(
      /\/\/ This file is autogenerated by the hyperschema compiler/,
      '// This file is autogenerated by the hyperschema compiler\n// Used by generated/hrpc/index.js'
    )
    fs.writeFileSync(hrpcMessagesPath, updatedContent)
    console.log('Generated generated/hrpc/messages.js')
  }

  // Generate HRPC index.js from hrpc.json
  try {
    const builder = HRPCBuilder.from(schemaDir, hrpcDir)
    // Generate directly to the output directory
    HRPCBuilder.toDisk(builder, outputDir)
    console.log('Generated generated/hrpc/index.js')
  } catch (err) {
    console.error('Error generating HRPC index.js:', err.message)
    console.error('Make sure src/hrpc/hrpc.json is valid and schema is generated first')
    process.exit(1)
  }

  // Set VERSION from schema.json, last (HRPCBuilder rewrites messages.js). Otherwise it
  // would be 1, since hyperschema's own counter always starts over (see above).
  const schemaVersion = schemaData.version || 1
  const pinnedMessages = fs.readFileSync(hrpcMessagesPath, 'utf8')
    .replace(/\/\/ Schema Version: \d+/, `// Schema Version: ${schemaVersion}`)
    .replace(/const VERSION = \d+/, `const VERSION = ${schemaVersion}`)
  fs.writeFileSync(hrpcMessagesPath, pinnedMessages)
}

module.exports = generateHrpc
